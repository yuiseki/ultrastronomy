"""Exploratory analyses over the contributed records. Nothing here decides a verdict.

The sub-screens below were written down before their results were looked at,
but after the full screen's results were known. Read what they give as a
description of the pooled sample, not as a test.
"""

from __future__ import annotations

from pathlib import Path

from .intervals import wilson
from .run import read_json

HOST = ("galaxy_host", "nuclear")
SAMPLING = ("long_lived", "well_sampled")
COLOUR = ("blue_at_peak", "no_reddening")

# name -> (what it asks, predicate over the dict of criteria met)
SCREENS = {
    "host": ("a galaxy host and a nuclear position",
             lambda m: all(m[c] for c in HOST)),
    "host + sampling": ("the above, lasting 60 days with 10 detections",
                        lambda m: all(m[c] for c in HOST + SAMPLING)),
    "colour": ("blue at peak and not reddening, nothing else",
               lambda m: all(m[c] for c in COLOUR)),
    "5 of 6": ("the rule the runs locked: any five criteria",
               lambda m: sum(m.values()) >= 5),
    "6 of 6": ("every criterion",
               lambda m: all(m.values())),
}


def pooled_objects(contributions: Path) -> list[dict]:
    """Every object of every real-data record, once, with the criteria it met.

    Reads the records only. A record is in `contributions/` because its
    results were recomputed from re-downloaded data when it was reviewed.
    """
    seen, out = set(), []
    for path in sorted(contributions.glob("*/results.json")):
        results = read_json(path)
        if results["data_source"] != "fink":
            continue
        for o in results["objects"]:
            if o["id"] in seen:
                continue
            seen.add(o["id"])
            criteria = o["met"] or {name: False for name in HOST + SAMPLING + COLOUR}
            out.append({"id": o["id"], "role": o["role"], "label": o["label"], "met": criteria})
    return out


def ablation(objects: list[dict], positive_groups: list[str]) -> dict:
    """For each sub-screen: how many positives and how many of each stratum it keeps."""
    positives = [o for o in objects if o["role"] == "truth" and o["label"] in positive_groups]
    strata = sorted({o["label"] for o in objects if o["role"] == "background"})
    table = {}
    for name, (_, keep) in SCREENS.items():
        row = {"positives": {"passed": sum(keep(o["met"]) for o in positives), "n": len(positives)}}
        for s in strata:
            members = [o for o in objects if o["role"] == "background" and o["label"] == s]
            row[s] = {"passed": sum(keep(o["met"]) for o in members), "n": len(members)}
        table[name] = row
    return {"strata": strata, "table": table}


def ablation_markdown(result: dict) -> str:
    strata = result["strata"]
    lines = ["| Screen | Asks for | Positives | " + " | ".join(f"`{s}`" for s in strata) + " |",
             "|---|---|---|" + "---|" * len(strata)]
    for name, (asks, _) in SCREENS.items():
        row = result["table"][name]
        cells = [f"{row[k]['passed']} of {row[k]['n']}" for k in ["positives"] + strata]
        lines.append(f"| {name} | {asks} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def pool_markdown(pooled: dict) -> str:
    strata = sorted(pooled["table"][0]["background"]) if pooled["table"] else []
    lines = [f"Runs: {pooled['runs']}. Background objects, each counted once: {pooled['background_objects']}.", "",
             "| Score | " + " | ".join(f"`{s}`" for s in strata) + " |", "|---|" + "---|" * len(strata)]
    for row in pooled["table"]:
        cells = []
        for s in strata:
            c = row["background"][s]
            lo, hi = wilson(c["passed"], c["n"])
            cells.append(f"{c['passed']} of {c['n']} ({100 * lo:.0f}-{100 * hi:.0f}%)")
        lines.append(f"| {row['threshold']} or more | " + " | ".join(cells) + " |")
    lines.append("\nIn brackets: the 95% interval of the pass rate.")
    return "\n".join(lines) + "\n"


def results_markdown(contributions: Path, mission: dict, pooled: dict) -> str:
    """RESULTS.md: where the mission stands, generated from the records."""
    objects = pooled_objects(contributions)
    positives = [o for o in objects if o["role"] == "truth" and o["label"] in mission["positive_groups"]]
    return "\n".join([
        "# Results so far",
        "",
        "Generated by `uv run ultra results --write` from the records in `contributions/`. Do not edit by hand; a test fails if this file is out of date.",
        "",
        f"Mission: {mission['title']}.",
        "",
        "## Background pass rates",
        "",
        pool_markdown(pooled),
        "The known objects are the same in every run and are not pooled: "
        f"{sum(sum(o['met'].values()) >= 5 for o in positives)} of {len(positives)} positives score 5 or more.",
        "",
        "## What each part of the screen does",
        "",
        "Exploratory. These sub-screens were chosen after the full screen's results were known, and the sample is small.",
        "",
        ablation_markdown(ablation(objects, mission["positive_groups"])),
        "Read the first row against the fourth. If two host flags alone keep as many positives and as little background "
        "as the locked rule, the colour and duration criteria are not adding anything this sample can show.",
        "",
    ])
